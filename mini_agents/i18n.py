def set_lang(lang: str):
    """设置当前语言：zh / en（其他值按前缀判断，无法识别则回退 zh）。"""
    global _LANG
    _LANG = "en" if str(lang).lower().startswith(("e", "en")) else "zh"


def init_from_env():
    """入口程序在启动时调用：从 MINI_LANG 环境变量初始化语言。"""
    set_lang(os.getenv("MINI_LANG", "zh"))


def get_lang() -> str:
    if _LANG is None:
        init_from_env()
    return _LANG


def t(_key: str, **kwargs) -> str:
    """取文案：当前语言缺失时回退中文，再缺失回退键名本身。支持 {占位符}。

    首参命名为 _key 以避免与文案占位符（如 {key}、{name}）撞名。
    """
    lang = get_lang()
    template = _STRINGS[lang].get(_key) or _STRINGS["zh"].get(_key) or _key
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            return template
    return template
